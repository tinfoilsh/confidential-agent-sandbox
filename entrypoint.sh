#!/bin/bash
# Install this boot's attested SSH key, unlock the disk, mount its state, and start systemd.
set -euo pipefail

disk=/mnt/disk
credentials=/run/workspace

umask 022
install -d -m 0711 "$credentials"
# OpenSSH reads the PKCS#8 key the CVM attests, so sshd and reverse SSH prove the same key.
install -m 0600 /run/tinfoil/keys/host-ssh/private_key.pem "$credentials/host_key"
# Login authority comes only from the measured key, including on an existing disk.
/usr/local/libexec/workspace-keys
# Public launch configuration lets the owner reach this boot before unlocking it.
reverse=
unlock_config=/etc/ssh/sshd-unlock.conf
if [[ ${NO_MONITOR:-} == 1 ]]; then
    sed 's/ListenAddress 127.0.0.1/ListenAddress 0.0.0.0/' "$unlock_config" > "$credentials/sshd-unlock.conf"
    unlock_config=$credentials/sshd-unlock.conf
else
    (
        child=
        trap '[[ -z "$child" ]] || kill "$child" 2>/dev/null; exit 0' TERM INT
        while true; do
            /usr/bin/ssh -NT -F /etc/ssh/monitor-reverse.conf monitor &
            child=$!
            wait "$child" || true
            sleep 2 &
            child=$!
            wait "$child" || true
        done
    ) &
    reverse=$!
fi
bootstrap_ssh=
attestation=
trap 'kill ${reverse:+"$reverse"} ${bootstrap_ssh:+"$bootstrap_ssh"} ${attestation:+"$attestation"} 2>/dev/null; wait || true' EXIT
if [[ -S /run/tinfoil/volumes/workspace/control.sock ]]; then
    install -d -m 0755 /run/sshd
    /usr/sbin/sshd -D -e -f "$unlock_config" &
    bootstrap_ssh=$!
    /usr/local/libexec/workspace-attestation &
    attestation=$!
    while [[ -S /run/tinfoil/volumes/workspace/control.sock ]]; do
        kill -0 "$bootstrap_ssh" "$attestation"
        sleep 0.2
    done
    kill "$bootstrap_ssh"
    wait "$bootstrap_ssh" || true
    bootstrap_ssh=
fi
# A locked volume is a read-only placeholder; the worker mounts writable ext4.
findmnt -rn -M "$disk" -t ext4 -O rw >/dev/null || { echo "workspace is not unlocked" >&2; exit 1; }
# The pack names its closure without the hash here, which is what nix.conf reads.
install -d /nix/var/nix/profiles /nix/var/nix/daemon-socket
ln -sfn /tinfoil/models/nix/nix/var/nix/profiles/default /nix/var/nix/profiles/default
[[ -s $disk/machine-id ]] || systemd-id128 new > "$disk/machine-id"
[[ -d $disk/home ]] || cp -a /home "$disk/home"
[[ -d $disk/workspace ]] || install -d -o sandbox -g sandbox "$disk/workspace"
# Keyed by the image's package set, so a rebuilt image starts from a clean layer.
overlay=$disk/overlay/$(sha256sum /var/lib/dpkg/status | cut -c1-16)
mount --make-rprivate /
for dir in usr etc var opt; do
    install -d "$overlay/$dir/upper" "$overlay/$dir/work" /run/overlay
    mount -t overlay overlay -o "lowerdir=/$dir,upperdir=$overlay/$dir/upper,workdir=$overlay/$dir/work" /run/overlay
    # Runtime mounts such as resolv.conf and GPU libraries live under these directories.
    while IFS= read -r target; do
        printf -v target %b "$target"
        mount --rbind "$target" "/run/overlay${target#/"$dir"}"
    done < <(findmnt -rn -o TARGET | grep "^/$dir/")
    mount --move /run/overlay "/$dir"
done
mount --bind "$disk/machine-id" /etc/machine-id
mount --bind "$disk/home" /home
mount --bind "$disk/workspace" /workspace
# Seed after mounting home so existing disks discover the image's agent tools too.
runuser -u sandbox -- /usr/local/libexec/seed-agent-skills /home/sandbox
/usr/local/libexec/seed-agent-skills /root
runuser -u sandbox -- /usr/local/libexec/seed-agent-config /home/sandbox
/usr/local/libexec/seed-agent-config /root
# Discard files generated by images that kept boot-specific routes on the disk.
rm -f /etc/monitor/route.json /etc/ssh/ssh_config.d/monitor-route.conf
if [[ ${NO_MONITOR:-} == 1 ]]; then
    install -d /run/systemd/system
    ln -sf /dev/null /run/systemd/system/monitor-network.service
    ln -sf /dev/null /run/systemd/system/monitor-reverse.service
else
    # Keep DNS inside Monitor's TUN, including while its SSH connection is down.
    printf 'nameserver 100.127.255.2\noptions timeout:1 attempts:2\n' > /etc/resolv.conf
fi
# Leave device management with the CVM, while its cgroup submount stays writable.
mount -o remount,bind,ro /sys
if [[ -n $reverse || -n $attestation ]]; then kill ${reverse:+"$reverse"} ${attestation:+"$attestation"}; fi
wait || true
trap - EXIT
exec /sbin/init
